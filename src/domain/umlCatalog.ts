/**
 * Catálogo de diagramas disponibles en «Añadir diagrama».
 *
 * `support` indica cómo lo dibuja PlantUML:
 * - native: PlantUML tiene sintaxis propia para este diagrama.
 * - adapted: PlantUML no lo trae como tipo propio; la plantilla lo construye
 *   con elementos de otro diagrama (se explica en `note`).
 * - unavailable: el motor de PlantUML para navegador aún no lo dibuja.
 *
 * Todas las plantillas se probaron con @plantuml/core 1.2026.8.
 *
 * `visual` marca los tipos que tendrán editor visual (arrastrar y soltar).
 */
export type UmlCategory = 'uml' | 'architecture' | 'process'
export type UmlSupport = 'native' | 'adapted' | 'unavailable'

export type UmlDiagramType = {
  id: string
  name: string
  /** Nombre en inglés, como aparece en la bibliografía y en PlantUML. */
  english: string
  category: UmlCategory
  support: UmlSupport
  note?: string
  visual?: boolean
  template: string
}

