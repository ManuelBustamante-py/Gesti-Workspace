/** Diagrama vacío con las directivas de su tipo (@startgantt, @startmindmap…). */
export function blankTemplate(type: UmlDiagramType) {
  const rows = type.template.split('\n')
  const start = rows.find((row) => row.startsWith('@start'))
  const end = [...rows].reverse().find((row) => row.startsWith('@end'))
  return start && end ? lines(start, '', end) : BLANK_TEMPLATE
}

export function umlDiagramType(id: string) {
  return UML_DIAGRAM_TYPES.find((type) => type.id === id) ?? null
}
